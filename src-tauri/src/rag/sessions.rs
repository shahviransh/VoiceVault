use rusqlite::params;
use serde::{Deserialize, Serialize};

use super::db::{RagResult, RagState};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SessionRecord {
    pub id: String,
    pub mode: String,
    pub question: String,
    pub response: String,
    pub scores_json: String,
    pub created_at: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SaveSessionInput {
    pub mode: String,
    pub question: String,
    pub response: String,
    pub scores_json: String,
}

pub fn save_session(state: &RagState, input: SaveSessionInput) -> RagResult<SessionRecord> {
    let id = RagState::new_id();
    let created_at = RagState::now();
    let conn = state.conn.lock();
    conn.execute(
        "INSERT INTO sessions (id, mode, question, response, scores_json, created_at)
         VALUES (?1, ?2, ?3, ?4, ?5, ?6)",
        params![
            id,
            input.mode,
            input.question,
            input.response,
            input.scores_json,
            created_at
        ],
    )?;
    Ok(SessionRecord {
        id,
        mode: input.mode,
        question: input.question,
        response: input.response,
        scores_json: input.scores_json,
        created_at,
    })
}

pub fn list_sessions(state: &RagState, limit: i64) -> RagResult<Vec<SessionRecord>> {
    let conn = state.conn.lock();
    let mut stmt = conn.prepare(
        "SELECT id, mode, question, response, scores_json, created_at
         FROM sessions ORDER BY created_at DESC LIMIT ?1",
    )?;
    let rows = stmt.query_map([limit.max(1).min(200)], |r| {
        Ok(SessionRecord {
            id: r.get(0)?,
            mode: r.get(1)?,
            question: r.get(2)?,
            response: r.get(3)?,
            scores_json: r.get(4)?,
            created_at: r.get(5)?,
        })
    })?;
    let mut out = Vec::new();
    for row in rows {
        out.push(row?);
    }
    Ok(out)
}

pub fn export_session_markdown(state: &RagState, session_id: &str) -> RagResult<String> {
    let conn = state.conn.lock();
    let session = conn.query_row(
        "SELECT id, mode, question, response, scores_json, created_at FROM sessions WHERE id = ?1",
        [session_id],
        |r| {
            Ok(SessionRecord {
                id: r.get(0)?,
                mode: r.get(1)?,
                question: r.get(2)?,
                response: r.get(3)?,
                scores_json: r.get(4)?,
                created_at: r.get(5)?,
            })
        },
    )?;

    let scores: serde_json::Value =
        serde_json::from_str(&session.scores_json).unwrap_or(serde_json::json!({}));

    let md = format!(
        r#"# VoiceVault Session Debrief

- **Session ID:** {id}
- **Mode:** {mode}
- **Date:** {created}

## Question

{question}

## Response

{response}

## Scores

```json
{scores}
```

---
Generated by VoiceVault - practice from your own evidence, not generated answers.
"#,
        id = session.id,
        mode = session.mode,
        created = session.created_at,
        question = session.question,
        response = session.response,
        scores = serde_json::to_string_pretty(&scores).unwrap_or_else(|_| session.scores_json.clone()),
    );

    Ok(md)
}
